// PROTOTYPE, throwaway: writes the same seven Dossiers into dossier-git/ in three Personal database layouts, for lab1 #33.
// Hindsight carries the stub re-Launch, so each layout shows where a re-Launch lands. Run: node dossier-git.mjs
import { mkdirSync, rmSync, writeFileSync } from 'node:fs';
import { dirname } from 'node:path';
import { PRODUCTS, withRelaunch } from './dossiers.mjs';
import { gitFiles, GIT_BASE, gitPaths } from './dossier-render.mjs';

const root = new URL('./dossier-git/', import.meta.url).pathname;
rmSync(root, { recursive: true, force: true });
const products = PRODUCTS.map(withRelaunch);
const files = gitFiles(products);
const LAYOUTS = {
  1: ['One file per Product', 'products/<domain>.md holds the Dossier, what each source said, the Registration lines and your Notes, in that order.'],
  2: ['A folder per Product, a file per writer', 'products/<domain>/ holds dossier.md (the Discord message, mirrored), registration.md (bot, appended) and notes.md (yours alone).'],
  3: ['By date', 'dossiers/<day>-<domain>.md is the Dossier as of each Launch (a re-Launch is a new file), registrations.md is one log for every Product, notes/<domain>.md is yours.'],
};
files['README.md'] = [
  '# PROTOTYPE, wipe me: three Personal database layouts for the same Dossiers',
  '',
  'Answers part of [How does a Dossier read in its Product post, and how is it kept in git?](https://github.com/ultrasadness/lab1/issues/33). Generated by `node dossier-git.mjs` from `dossiers.mjs`; the Registration lines are stubs, and so is Hindsight\'s Nov 4 re-Launch.',
  '',
  ...Object.entries(LAYOUTS).flatMap(([n, [name, how]]) => [`## ${n}. ${name}`, '', how, '', products.map((p) => `- [${p.name}](${GIT_BASE}/${gitPaths(p)[n]})`).join('\n'), '']),
].join('\n');
for (const [path, body] of Object.entries(files)) {
  mkdirSync(dirname(root + path), { recursive: true });
  writeFileSync(root + path, body);
}
console.log(`wrote ${Object.keys(files).length} files under dossier-git/`);
